// Isolated visual prototype acceptance. No sidecar, GitHub, or project endpoints.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { createServer } from 'vite'
import vue from '@vitejs/plugin-vue'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.RUNDOCK_PLAYWRIGHT_MODULE || 'playwright')
const evidence = path.join(root, 'outputs/release-options-preview')
await mkdir(evidence, { recursive: true })
// Keep Vite discovery away from large local build caches in the repository.
const fixtureRoot = path.join(root, '.tmp/release-options-preview')
await mkdir(fixtureRoot, { recursive: true })
const html = await readFile(path.join(root, 'design/release-options/index.html'), 'utf8')
await writeFile(path.join(fixtureRoot, 'index.html'), html.replace('/design/release-options/main.ts', '/@fs/' + root.replaceAll('\\', '/') + '/design/release-options/main.ts'))
const server = await createServer({ configFile: false, root: fixtureRoot, plugins: [vue()], resolve: { alias: { '@': path.join(root, 'src') } },
  optimizeDeps: { entries: ['index.html'] },
  server: { host: '127.0.0.1', port: 19483, strictPort: false, open: false, fs: { allow: [root] } } })
await server.listen()
const browser = await chromium.launch({ channel: process.env.RUNDOCK_BROWSER_CHANNEL || 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 }, locale: 'zh-CN' })
const errors = [], unexpected = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/*', async route => {
  const request = route.request(), url = new URL(request.url())
  if (url.pathname.startsWith('/api/') || !['127.0.0.1', 'localhost'].includes(url.hostname) || request.method() !== 'GET') {
    unexpected.push(`${request.method()} ${url.href}`)
    return route.abort()
  }
  return route.continue()
})
const report = { passed: false, boundary: 'isolated Vue prototypes; no API, profile, or release calls', checks: [] }
const trigger = page.getByRole('button', { name: '选择构建与发布方式', exact: true })
const result = page.locator('.result-path')
const select = name => page.getByRole('button', { name, exact: true }).click()
const localBranch = '本地构建 使用本机环境打包'
const localDestination = '仅保存在本机 不上传 GitHub'
const variantLabel = text => page.locator('.variant-picker label').filter({ hasText: text })
const scenarioLabel = text => page.locator('.scenario-cards label').filter({ hasText: text })
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`)
  await trigger.waitFor()
  assert.match(await result.innerText(), /本地构建 → 发布到 GitHub Release/)
  await trigger.click()
  await select(localDestination)
  assert.equal(await page.locator('.cascade-column').count(), 3)
  await page.screenshot({ path: path.join(evidence, '01-cascade-expanded.png'), fullPage: true })
  await select('取消')
  assert.equal(await page.locator('.cascade-panel').count(), 0)
  assert.equal(await result.innerText(), '本地构建 → 发布到 GitHub Release')
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true)
  report.checks.push('three-level branching; cancel discards draft and restores trigger focus')

  await trigger.click()
  await select(localDestination)
  await page.keyboard.press('Escape')
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  await trigger.click()
  await select(localDestination)
  await select('保持当前版本 仅生成安装包')
  assert.equal(await result.innerText(), '本地构建 → 仅保存在本机 → 保持当前版本')
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  await page.screenshot({ path: path.join(evidence, '01-cascade-selected.png'), fullPage: true })
  report.checks.push('leaf selection collapses to the full result path; Escape cancels')

  await trigger.click()
  await select('GitHub 云端构建 构建后直接发布 Release')
  assert.equal(await result.innerText(), 'GitHub 云端构建 → 发布到 Release')
  await trigger.press('Enter')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('.cascade-column').count(), 2)
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('.cascade-column').count(), 3)
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  assert.equal(await result.innerText(), '本地构建 → 仅保存在本机 → 升级版本')
  report.checks.push('cloud leaf and keyboard-only local three-level selection work')

  await trigger.click()
  await select(localBranch)
  await page.getByRole('heading', { name: '选择方式，再简单一点。', exact: true }).click()
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  assert.match(await result.innerText(), /升级版本$/)
  report.checks.push('outside click closes without committing an unfinished branch')

  await variantLabel('第二种').click()
  assert.equal(await page.getByRole('radio', { name: '升级版本', exact: true }).isChecked(), true)
  assert.match(await result.innerText(), /升级版本$/)
  await scenarioLabel('本地构建并发布').click()
  await page.screenshot({ path: path.join(evidence, '02-flat-cards.png'), fullPage: true })
  const cards = await page.locator('.scenario-cards label').evaluateAll(items => items.map(el => {
    const r = el.getBoundingClientRect(); return { width: r.width, height: r.height, top: r.top }
  }))
  assert.ok(cards.every(r => Math.abs(r.width - cards[0].width) < 1 && Math.abs(r.height - cards[0].height) < 1 && r.top === cards[0].top))
  assert.equal(await page.locator('.version-row').count(), 0)
  await scenarioLabel('仅本地打包').click()
  assert.equal(await page.getByRole('radio', { name: '升级版本', exact: true }).isChecked(), true)
  await page.getByRole('radio', { name: '保持当前版本', exact: true }).check()
  await variantLabel('第一种').click()
  assert.equal(await result.innerText(), '本地构建 → 仅保存在本机 → 保持当前版本')
  report.checks.push('equal-height flat cards; shared selection across variants; local version preference retained')

  await variantLabel('第三种').click()
  const localCard = page.locator('.hybrid-cards .local-card')
  const hybridCards = page.locator('.hybrid-cards .route-card')
  assert.equal(await hybridCards.count(), 3)
  assert.equal(await page.locator('.version-row').count(), 0)
  const hybridRects = await hybridCards.evaluateAll(items => items.map(el => {
    const r = el.getBoundingClientRect(); return { width: r.width, height: r.height, top: r.top }
  }))
  assert.ok(hybridRects.every(r => Math.abs(r.width - hybridRects[0].width) < 1 && Math.abs(r.height - hybridRects[0].height) < 1 && r.top === hybridRects[0].top))
  await localCard.click()
  await page.getByRole('button', { name: '升级版本 生成新版本、本地提交和 Tag', exact: true }).click()
  assert.equal(await localCard.getAttribute('aria-expanded'), 'false')
  assert.match(await localCard.innerText(), /升级版本/)
  assert.match(await result.innerText(), /升级版本$/)
  assert.equal(await localCard.evaluate(el => el === document.activeElement), true)
  await localCard.click()
  await page.screenshot({ path: path.join(evidence, '03-card-cascade-expanded.png'), fullPage: true })
  await page.getByRole('button', { name: '取消版本选择', exact: true }).click()
  assert.match(await result.innerText(), /升级版本$/)
  await localCard.press('ArrowDown')
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  assert.match(await result.innerText(), /保持当前版本$/)
  await page.screenshot({ path: path.join(evidence, '03-card-cascade-selected.png'), fullPage: true })
  await localCard.click()
  await page.keyboard.press('Escape')
  assert.equal(await localCard.getAttribute('aria-expanded'), 'false')
  await localCard.click()
  await page.getByRole('heading', { name: '选择方式，再简单一点。', exact: true }).click()
  assert.equal(await localCard.getAttribute('aria-expanded'), 'false')
  await page.getByRole('button', { name: '云端构建并发布 GitHub → Release', exact: true }).click()
  await localCard.click()
  await page.keyboard.press('Escape')
  assert.equal(await result.innerText(), 'GitHub 云端构建 → 发布到 Release')
  assert.equal(await localCard.getAttribute('aria-pressed'), 'false')
  await localCard.click()
  await page.getByRole('button', { name: '本地构建并发布 本机 → GitHub Release', exact: true }).click()
  assert.equal(await localCard.getAttribute('aria-expanded'), 'false')
  assert.equal(await result.innerText(), '本地构建 → 发布到 GitHub Release')
  await localCard.click()
  await page.getByRole('button', { name: '保持当前版本 版本号不变，只生成安装包', exact: true }).click()
  await variantLabel('第二种').click()
  assert.equal(await page.getByRole('radio', { name: '保持当前版本', exact: true }).isChecked(), true)
  await variantLabel('第一种').click()
  report.checks.push('third variant keeps three equal parallel cards; local-only opens two version leaves; result returns to card; keyboard, cancellation, switching and shared state work')

  await page.getByRole('button', { name: '预览：仅本地打包', exact: true }).click()
  assert.match(await page.locator('.preview-feedback').innerText(), /没有创建构建或发布任务/)
  for (const name of ['PC 客户端', 'Android', 'Web＋服务端']) await page.locator('.platform-options label').filter({ has: page.getByRole('checkbox', { name, exact: true }) }).click()
  assert.equal(await page.locator('.preview-submit').isDisabled(), true)
  await page.locator('.platform-options label').filter({ has: page.getByRole('checkbox', { name: 'PC 客户端', exact: true }) }).click()
  report.checks.push('preview action is inert; empty target selection disables it')

  await page.setViewportSize({ width: 390, height: 844 })
  await trigger.click()
  assert.equal(await page.locator('.cascade-column').count(), 3)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: path.join(evidence, '01-cascade-mobile.png'), fullPage: true })
  await select('取消')
  await variantLabel('第二种').click()
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: path.join(evidence, '02-cards-mobile.png'), fullPage: true })
  await variantLabel('第三种').click()
  await localCard.click()
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: path.join(evidence, '03-card-cascade-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '升级版本 生成新版本、本地提交和 Tag', exact: true }).click()
  assert.match(await result.innerText(), /升级版本$/)
  report.checks.push('390px layout has no horizontal overflow in all three variants; mobile cascade commits normally')
  assert.deepEqual(errors, [])
  assert.deepEqual(unexpected, [])
  assert.equal(await page.evaluate(() => localStorage.length), 0)
  report.checks.push('no page errors, API/network mutations, or localStorage writes')
  report.passed = true
} catch (error) {
  report.error = String(error)
  await page.screenshot({ path: path.join(evidence, 'failure.png'), fullPage: true })
  throw error
} finally {
  await writeFile(path.join(evidence, 'acceptance.json'), JSON.stringify({ ...report, errors, unexpected }, null, 2))
  await browser.close()
  await server.close()
}
